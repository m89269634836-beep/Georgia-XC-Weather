"""Reconnaissance ONLY: DEM+tree cover ridge scan around Tbilisi.

Generated pixels are *hypothetical ridgeline survey locations*, not takeoffs.
No landing, roads, wires, airspace, gradient/launch safety established.
"""
import json,math,datetime
from pathlib import Path
import numpy as np
import rasterio
from rasterio.warp import reproject,Resampling
from rasterio.transform import from_origin,xy
from pyproj import Transformer
OUT=Path("data")
AOIS=[
 ("mtskheta_west","К западу от Мцхеты",41.845,44.665),
 ("saguramo","Сагурамо",41.882,44.801),
 ("martkopi","Марткопи",41.780,45.079),
 ("kojori","Коджори",41.665,44.713),
]
DIRS=[("N",0,-1,0),("NE",45,-1,1),("E",90,0,1),("SE",135,1,1),("S",180,1,0),
      ("SW",225,1,-1),("W",270,0,-1),("NW",315,-1,-1)]
VALID={20,30,60}
def copdem90(lat,lon):
 n=math.floor(lat);e=math.floor(lon)
 s=f"Copernicus_DSM_COG_30_{'N' if n>=0 else 'S'}{abs(n):02d}_00_{'E' if e>=0 else 'W'}{abs(e):03d}_00_DEM"
 return f"https://copernicus-dem-90m.s3.amazonaws.com/{s}/{s}.tif"
def worldcover(lat,lon):
 n=math.floor(lat/3)*3;e=math.floor(lon/3)*3
 t=f"{'N' if n>=0 else 'S'}{abs(n):02d}{'E' if e>=0 else 'W'}{abs(e):03d}"
 return f"https://esa-worldcover.s3.eu-central-1.amazonaws.com/v200/2021/map/ESA_WorldCover_10m_2021_v200_{t}_Map.tif"
TOUTM=Transformer.from_crs("EPSG:4326","EPSG:32638",always_xy=True)
TOLL=Transformer.from_crs("EPSG:32638","EPSG:4326",always_xy=True)
def grid(url,transform,n,dtype,resampling,nodata):
 target=np.full((n,n),nodata,dtype=dtype)
 with rasterio.Env(GDAL_DISABLE_READDIR_ON_OPEN="EMPTY_DIR",GDAL_HTTP_MAX_RETRY="2"):
  with rasterio.open(url) as src:
    reproject(source=rasterio.band(src,1),destination=target,
     dst_transform=transform,dst_crs="EPSG:32638",dst_nodata=nodata,
     resampling=resampling,num_threads=1)
 return target
report={"generated_utc":datetime.datetime.now(datetime.timezone.utc).isoformat(),
"dataset_dem":"Copernicus DSM GLO-90, native ~90 m, sampling onto 90 m UTM grid",
"dataset_landcover":"ESA WorldCover 2021 v200, sampled to 90 m (indicative only)",
"method":"Select >~70 m drop in 360 m, open candidate crest with 600m+ continuous similar-facing slope and no higher terrain immediately behind; several self-imposed screening constraints.",
"disclaimer":"NO road, access, exact launch, landing, airspace, rotor, power-line or current satellite verification. Candidate positions are generated by a raster heuristic, not established flying sites.",
"regions":{},"candidates":[],"errors":[]}
for key,name,lat,lon in AOIS:
 try:
  x0,y0=TOUTM.transform(lon,lat)
  step=90;n=112;halfw=n*step/2
  trans=from_origin(x0-halfw,y0+halfw,step,step)
  z=grid(copdem90(lat,lon),trans,n,"float32",Resampling.bilinear,-9999)
  lc=grid(worldcover(lat,lon),trans,n,"uint8",Resampling.nearest,0)
  if np.mean(z<-5000)>.03: raise RuntimeError("Too many missing DEM cells")
  spots=[]
  for r in range(12,n-12):
   for c in range(12,n-12):
    if not(550<=z[r,c]<=1600 and int(lc[r,c]) in VALID):continue
    cover=lc[r-3:r+4,c-3:c+4]
    tree=np.mean(cover==10);open_=np.mean(np.isin(cover,[20,30,60]))
    if tree>.11 or open_<.8:continue
    slope=np.hypot(float(z[r,c+1]-z[r,c-1]),float(z[r+1,c]-z[r-1,c]))/(2*step)
    if slope>.48:continue
    for dirName,deg,dr,dc in DIRS:
     frontz=float(z[r+dr*4,c+dc*4])
     dz=float(z[r,c]-frontz)
     if dz<75 or dz>280:continue
     behind=float(z[r-dr*5,c-dc*5])
     if behind>z[r,c]+110:continue
     # Continuity along local cross-slope direction
     rr,cc=-dc,dr
     consistent=0
     for k in range(-5,6):
      i=r+rr*k;j=c+cc*k
      if not (0<=i+dr*4<n and 0<=j+dc*4<n):continue
      drop=float(z[i,j]-z[i+dr*4,j+dc*4])
      if drop>=55 and abs(float(z[i,j]-z[r,c]))<90 and int(lc[i,j]) in VALID:consistent+=1
     if consistent<7:continue
     xx,yy=xy(trans,r,c);xlon,xlat=TOLL.transform(xx,yy)
     dist=math.hypot((xlat-41.716)*111,(xlon-44.783)*83)
     if dist>75:continue
     score=dz*0.65+consistent*4-open_*0 + (1-tree)*12 - min(dist,75)*.10
     spots.append({"id":f"{key}_{dirName}_{r}_{c}","region":name,
         "lat":round(xlat,6),"lon":round(xlon,6),
         "facing_deg":deg,"possible_face":dirName,"dem_m_amsl":round(float(z[r,c])),
         "drop_360m_m":round(dz),"ridge_continuity_approx_m":consistent*90,
         "open_landcover_nearby_pct":round(open_*100),
         "treecover_nearby_pct":round(tree*100),
         "approx_straight_distance_to_Tbilisi_km":round(dist,1),
         "rough_score":round(score,1)})
  spots.sort(key=lambda s:s["rough_score"],reverse=True)
  picked=[]
  for s in spots:
   if any(math.hypot((s["lat"]-x["lat"])*111000,(s["lon"]-x["lon"])*83000)<1500 for x in picked):continue
   picked.append(s)
   if len(picked)>=3:break
  report["regions"][key]={"label":name,"source_grid_cells":int(n*n),
     "raw_geom_candidates":len(spots),"top":picked}
  report["candidates"].extend(picked)
  print("SCOUT_OK",name,"raw",len(spots),"selected",len(picked),flush=True)
 except Exception as exc:
  report["errors"].append({"region":name,"error":str(exc)[:400]})
  print("SCOUT_FAIL",name,str(exc)[:260],flush=True)
OUT.mkdir(exist_ok=True)
(OUT/"dynamic_tbilisi_dem_scout.json").write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding="utf-8")
print("TOTAL",len(report["candidates"]),"errors",len(report["errors"]),flush=True)
